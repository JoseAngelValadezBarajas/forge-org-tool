import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const file = resolve('packages/tokens/tokens.json');
const output = resolve('packages/tokens/src/tokens.css');
const data = JSON.parse(readFileSync(file, 'utf8'));
const name = (s) => s.replace(/[A-Z]/g, (v) => '-' + v.toLowerCase());
const declarations = (obj, prefix = '') =>
  Object.entries(obj)
    .map(([k, v]) => `  --forge-${prefix}${name(k)}: ${v};`)
    .join('\n');
const content = `/* GENERATED by npm run generate:tokens. Do not edit. */\n:root, [data-theme="dark"] {\n${declarations(data.colors.dark)}\n${declarations(data.semantic.dark)}\n}\n[data-theme="light"] {\n${declarations(data.colors.light)}\n${declarations(data.semantic.light)}\n}\n:root {\n${declarations(data.spacing, 'space-')}\n${declarations(data.radius, 'radius-')}\n${declarations(data.type, 'font-')}\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) {
    console.error('Design tokens CSS is stale; run npm run generate:tokens');
    process.exit(1);
  }
  console.log('Design tokens CSS matches the source JSON');
} else {
  writeFileSync(output, content);
  console.log(`Wrote ${output}`);
}
