import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';

const webSrc = path.resolve(import.meta.dirname, '../../apps/web/src');

// V1 components that @corefoundry-labs/forge-ui 1.1.0 replaces with a V2 equivalent.
const REPLACED = {
  Button: 'ButtonV2',
  Card: 'CardV2',
  Input: 'TextInputV2',
  Select: 'SelectV2',
  Checkbox: 'CheckboxV2',
  Switch: 'SwitchV2',
  Badge: 'BadgeV2',
  StatusChip: 'BadgeV2',
  Dialog: 'DialogV2',
  Tabs: 'TabsV2',
  Alert: 'AlertV2',
  ErrorState: 'FeedbackStateV2',
  LoadingState: 'FeedbackStateV2',
};

function sourceFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'component-gallery' ? [] : sourceFiles(full);
    return /\.tsx?$/.test(entry.name) && !/\.test\./.test(entry.name) ? [full] : [];
  });
}

test('the app uses the V2 Forge components wherever a V2 equivalent exists', () => {
  const offenders = [];
  for (const file of sourceFiles(webSrc)) {
    const source = fs.readFileSync(file, 'utf8');
    for (const match of source.matchAll(
      /import\s*\{([^}]*)\}\s*from\s*'@corefoundry-labs\/forge-ui'/g,
    )) {
      for (const raw of match[1].split(',')) {
        const name = raw.trim().replace(/^type\s+/, '');
        if (REPLACED[name])
          offenders.push(`${path.relative(webSrc, file)}: ${name} -> ${REPLACED[name]}`);
      }
    }
  }
  assert.deepEqual(offenders, []);
});

test('the application theme is generated by Theme Engine V2 and applied through ThemeScope', () => {
  const theme = fs.readFileSync(path.join(webSrc, 'app/theme.tsx'), 'utf8');
  const app = fs.readFileSync(path.join(webSrc, 'app/App.tsx'), 'utf8');
  assert.match(theme, /@corefoundry-labs\/forge-tokens\/theme-v2/);
  assert.match(theme, /createTheme\(/);
  assert.match(app, /<ThemeScope\b/);
});
